/**
 * Fault list generator: `tools/sources/nav20.faults.source.json` (fault numbers of the Navigator 2.0 operating manual) to
 * `src/lib/fault-messages.json`, which maps a fault number to an English text template of the dictionary. Fails when a text lacks a
 * translation (run `npm run translate:strings` or add it to the dictionary).
 *
 * Usage: `npm run build:faults`
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import dictionaryFile from '../src/lib/dictionary.json';
import { type Dictionary, missingLanguages } from '../src/lib/translations';

/** One entry of the source file. */
interface SourceEntry {
    code: number;
    de: string;
    en: string;
}

/** The source file. */
interface FaultSource {
    document: string;
    sensors: SourceEntry[];
    faults: SourceEntry[];
    events: SourceEntry[];
}

/** What the runtime needs for one fault number: a template of the dictionary and, for sensor faults, the sensor's name. */
export interface FaultMessage {
    text: string;
    sensor?: string;
}

/**
 * Build the code to message map. Sensor faults come in pairs: the first code is a short circuit, the next one an interruption.
 *
 * @param source the parsed source file
 */
export function buildFaultMessages(source: FaultSource): Record<string, FaultMessage> {
    const messages: Record<string, FaultMessage> = {};
    const add = (code: number, message: FaultMessage): void => {
        if (messages[String(code)]) {
            throw new Error(`Fault ${code} is listed twice`);
        }
        messages[String(code)] = message;
    };
    for (const sensor of source.sensors) {
        add(sensor.code, { text: '{sensor}: short circuit', sensor: sensor.en });
        add(sensor.code + 1, { text: '{sensor}: interruption', sensor: sensor.en });
    }
    for (const entry of [...source.faults, ...source.events]) {
        add(entry.code, { text: entry.en });
    }
    return messages;
}

/** CLI entry. */
function main(): void {
    const root = path.join(__dirname, '..');
    const source = JSON.parse(
        fs.readFileSync(path.join(root, 'tools', 'sources', 'nav20.faults.source.json'), 'utf8'),
    ) as FaultSource;
    const messages = buildFaultMessages(source);
    const texts = new Set<string>(['Fault {code}', 'Fault {code} (unknown)']);
    for (const message of Object.values(messages)) {
        texts.add(message.text);
        if (message.sensor) {
            texts.add(message.sensor);
        }
    }
    const missing = [...texts].filter(text => missingLanguages(text, dictionaryFile as Dictionary).length);
    if (missing.length) {
        console.error(`${missing.length} texts lack translations, first: "${missing[0]}"`);
        process.exit(1);
    }
    const out = {
        $comment:
            'Generated by tools/build-faults.ts from tools/sources/nav20.faults.source.json - do not edit. ' +
            `Fault numbers and names from: ${source.document}`,
        messages,
    };
    fs.writeFileSync(path.join(root, 'src', 'lib', 'fault-messages.json'), `${JSON.stringify(out, null, 4)}\n`);
    console.log(`faults: ${Object.keys(messages).length} fault numbers`);
}

if (require.main === module) {
    main();
}
